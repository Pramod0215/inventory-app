const preferenceKey = 'inventory-preferences';
const I18nContext = createContext({
  language: 'en',
  t: (text) => text,
});
const PreferencesContext = createContext({
  language: 'en',
  theme: 'dark',
  setLanguage: () => {},
  toggleTheme: () => {},
});

function readPreferences() {
  try {
    const saved = JSON.parse(localStorage.getItem(preferenceKey) || '{}');
    return {
      language: ['en', 'hi', 'bn'].includes(saved.language) ? saved.language : 'en',
      theme: ['light', 'dark'].includes(saved.theme) ? saved.theme : 'dark',
    };
  } catch {
    return { language: 'en', theme: 'dark' };
  }
}

export function I18nProvider({ children }) {
  const [preferences, setPreferences] = useState(readPreferences);
  const { language, theme } = preferences;

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dataset.theme = theme;
    try {
      localStorage.setItem(preferenceKey, JSON.stringify(preferences));
    } catch (error) {
      console.error('Unable to save display preferences:', error);
    }
  }, [preferences, language, theme]);

  const setLanguage = useCallback((nextLanguage) => {
    if (!['en', 'hi', 'bn'].includes(nextLanguage)) return;
    setPreferences((current) => ({ ...current, language: nextLanguage }));
  }, []);
  const toggleTheme = useCallback(() => {
    setPreferences((current) => ({
      ...current,
      theme: current.theme === 'dark' ? 'light' : 'dark',
    }));
  }, []);
  const t = useCallback((text) => translations[language]?.[text] || text, [language]);

  const translationValue = useMemo(() => ({
    language,
    t,
  }), [language, t]);
  const preferencesValue = useMemo(() => ({
    language,
    theme,
    setLanguage,
    toggleTheme,
  }), [language, theme, setLanguage, toggleTheme]);

  return (
    <I18nContext.Provider value={translationValue}>
      <PreferencesContext.Provider value={preferencesValue}>
        {children}
      </PreferencesContext.Provider>
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

export function usePreferences() {
  return useContext(PreferencesContext);
}
